def build_html(dev, episodes, models, out, audio_dir="demo_curated/audio", set_="dev_80"):
    """Interactive viewer: conversation chips, one card per model (note, outcome, audio, color-coded lines)."""
    from .chat_gui import CURATED
    notes = {k: (t, n) for k, t, n in CURATED}
    data = {"episodes": [], "models": []}
    for R, run, ck, label in models:
        key = "base" if run == "R0" else f"{run}/{ck}"
        title, note = notes.get(key, (label, ""))
        data["models"].append({"run": run, "ck": ck, "label": label, "title": title, "note": note})
    for eid in episodes:
        ev = json.loads((dev / "episodes" / f"{eid}.json").read_text())["events"]
        regs = regions(ev)
        rows = {}
        for R, run, ck, label in models:
            items, sc = model_items(ev, regs, Path(R) / "eval_raw" / run / set_ / ck, eid)
            m4a = f"{audio_dir}/{eid}__{run}__{ck}.m4a"
            rows[f"{run}|{ck}"] = {"items": items, "outcome": outcome_line(sc),
                                   "audio": m4a if (Path(out).parent / m4a).exists() else None}
        data["episodes"].append({"id": eid, "type": ev["type"], "title": TITLES.get(ev["type"], ev["type"]),
                                 "header": episode_header(ev, regs), "rows": rows})
    Path(out).write_text(VIEWER.replace("__DATA__", json.dumps(data)))


