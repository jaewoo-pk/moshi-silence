"""Readable transcripts of generated conversations: the script (user / friend) merged with what a
model actually said (its text stream), with the hold windows, release points and scored outcomes.

  python -m silence.transcript_gen --dev ~/repo/moshi-silence/data/dev --out results/transcripts.md

Moshi lines are grouped from the model's word timestamps (a gap > 0.8 s starts a new line) and tagged
  [script]    outside the scored windows, where the eval replays the scripted Moshi
  (no tag)    generated by the model
  ✗ HOLD      generated inside a hold, after the 2.5 s ack grace and before the release
"""
