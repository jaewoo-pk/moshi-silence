def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dev", required=True)
    ap.add_argument("--out", default="results/transcripts.md")
    ap.add_argument("--episodes", nargs="+", default=EPISODES)
    ap.add_argument("--html", help="also write the interactive viewer here (e.g. results/transcripts.html); "
                                   "audio from results/demo_curated (run demo_phase1 --curated first)")
    a = ap.parse_args()
    dev = Path(a.dev).expanduser()
    head = ["# Generated conversations: transcripts", "",
            "Dev conversations (unseen scripts). For each model: what the user / friend said (scripted) and what the model "
            "said, with times in seconds. `[script]` = outside the scored windows, where the eval replays the scripted "
            "Moshi; untagged MOSHI lines are the model's own; `✗ HOLD` = talking during a requested silence. "
            "Words come from Moshi's text stream (what it meant to say); listen in results/demo for the audio.", ""]
    body = [transcript(e, dev, MODELS) for e in a.episodes]
    Path(a.out).write_text("\n".join(head + body))
    if a.html:
        build_html(dev, DEMO_EPISODES, MODELS, a.html)
        print(f"wrote {a.html} ({len(DEMO_EPISODES)} conversations x {len(MODELS)} models)")
    print(f"wrote {a.out} ({len(a.episodes)} conversations x {len(MODELS)} models)")


if __name__ == "__main__":
    main()
