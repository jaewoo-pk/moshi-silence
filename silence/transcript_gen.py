def utterances(words, gap=0.8):
    out = []
    for w, t in words:
        if w in ("<s>", "</s>"):
            continue
        if out and t - out[-1]["end"] <= gap:
            out[-1]["text"] += " " + w
            out[-1]["end"] = t
        else:
            out.append({"t": t, "end": t, "text": w})
    return out


def regions(ev):
    th = Thresholds()
    rs = []
    for h in ev.get("holds", []):
        rel = h["release"]
        tol = th.timer_tol(rel["N"]) if rel["kind"] == "timer" else th.cue_pre
        rs.append({"instr_end": h["instr_end"], "ref": rel["ref"], "kind": rel["kind"], "N": rel.get("N"),
                   "viol": (h["instr_end"] + th.grace, rel["ref"] - tol)})
    return rs


def outcome_line(sc):
    parts = []
    for i, h in enumerate(sc["holds"]):
        tag = f"hold {i + 1}: " if len(sc["holds"]) > 1 else "hold: "
        v = {True: f"talked ({h['words_in_hold']} words)", False: "stayed silent", None: "(too short to score)"}[h["violated"]]
        res = {"on_time": "resumed on time", "late": "resumed late", "no_onset": "didn't resume"}.get(h["outcome"], h["outcome"])
        if h.get("latency") is not None and h["outcome"] != "no_onset":
            res += f" ({h['latency']:+.1f} s)"
        parts.append(tag + v + ", " + res)
    for i, r in enumerate(sc["responses"]):
        parts.append(f"question {i + 1}: " + ("answered" + (f" (+{r['latency']:.1f} s)" if r.get("latency") is not None else "")
                                              if r["responded"] else "not answered"))
    if sc.get("interrupt_onsets"):
        parts.append(f"{sc['interrupt_onsets']} interruption(s)")
    return "; ".join(parts) or "(nothing scored)"


def model_items(ev, regs, d, eid):
    """Merged timeline for one model on one episode: [{t, who, text, tag}], plus its score row."""
    gen = json.loads((d / f"{eid}.json").read_text())
    sc = next(r for r in map(json.loads, (d / "scores.jsonl").read_text().splitlines()) if r and r["id"] == eid)
    free = gen["free"]
    items = [{"t": t["t"][0], "who": "FRIEND" if t["spk"] == "friend" else "USER", "text": t["text"], "tag": ""}
             for t in ev.get("human_turns", [])]
    for u in utterances(gen["words"]):
        in_free = any(a <= u["t"] < b for a, b in free)
        tag = "script" if not in_free else ("hold" if any(r["viol"][0] <= u["t"] < r["viol"][1] for r in regs) else "")
        items.append({"t": u["t"], "who": "MOSHI", "text": u["text"], "tag": tag})
    for r in regs:
        items.append({"t": r["instr_end"] + 1e-3, "who": "", "text": "hold starts: Moshi should stay silent", "tag": "mark"})
        items.append({"t": r["ref"] - 1e-3, "who": "", "text": f"Moshi should speak again ({r['ref']:.1f} s)", "tag": "mark"})
    items.sort(key=lambda x: x["t"])
    return items, sc


def episode_header(ev, regs):
    out = []
    for r in regs:
        what = f"timer, N = {r['N']} s" if r["kind"] == "timer" else "until the user's cue"
        out.append(f"Hold: Moshi should be silent from {r['instr_end']:.1f} s ({what}) and speak again at {r['ref']:.1f} s.")
    return out or ["No hold: Moshi should answer normally."]


def transcript(eid, dev, models, set_="dev_80"):
    ev = json.loads((dev / "episodes" / f"{eid}.json").read_text())["events"]
    regs = regions(ev)
    lines = [f"## {eid} · {TITLES.get(ev['type'], ev['type'])} ({ev['type']})", ""] + episode_header(ev, regs) + [""]
    for R, run, ck, label in models:
        items, sc = model_items(ev, regs, Path(R) / "eval_raw" / run / set_ / ck, eid)
        lines += [f"### {label}", "", f"*Scored: {outcome_line(sc)}*", "", "```"]
        for it in items:
            if it["tag"] == "mark":
                lines.append(f"{it['t']:6.1f}            — {it['text']} —")
            else:
                tag = {"script": "   [script]", "hold": "   ✗ HOLD"}.get(it["tag"], "")
                lines.append(f"{it['t']:6.1f}  {it['who']:7} {it['text']}{tag}")
        lines += ["```", ""]
    return "\n".join(lines)


